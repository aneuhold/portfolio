/**
 * Which of the theme's text colors an element takes.
 */
export enum TextColor {
  /**
   * Sets no color, leaving it to the surrounding element.
   */
  Inherit = 'Inherit',
  /**
   * `--color-text-secondary` in `global-styles/global.css`.
   */
  Secondary = 'Secondary',
  /**
   * `--color-text-primary` in `global-styles/global.css`.
   */
  Primary = 'Primary'
}
